#!/usr/bin/env python3
"""Zip the release XCFrameworks and write a Swift package that serves them.

Without --url the package points at the zips beside it, for local use and for the
SwiftPM check in this folder. With --url it points at that address (a release's download
folder) and pins each zip by its SHA-256, the value `swift package compute-checksum` gives.
"""
import argparse
import hashlib
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "build/swiftpm/ArchiveKodec"
FRAMEWORKS = {
    "ArchiveKodecKit": ROOT / "archivekodec/build/XCFrameworks/release/ArchiveKodecKit.xcframework",
    "ArchiveKodecIo": ROOT / "archivekodec-io/build/XCFrameworks/release/ArchiveKodecIo.xcframework",
}


def zip_framework(source, target):
    """Zip keeping the bundle's symbolic links (macOS frameworks are versioned bundles)."""
    if not source.is_dir():
        raise RuntimeError(f"No XCFramework at {source}; run scripts/apple_frameworks.py first")
    target.unlink(missing_ok=True)
    if shutil.which("ditto"):
        command = ["ditto", "-c", "-k", "--sequesterRsrc", "--keepParent", source.name, target]
    else:
        command = ["zip", "-q", "-r", "-y", target, source.name]
    subprocess.run([str(part) for part in command], cwd=source.parent, check=True)


def manifest(targets):
    lines = [
        "// swift-tools-version:5.9",
        "// Generated by integration-tests/swift-package/package.py.",
        "import PackageDescription",
        "",
        "// Link ArchiveKodecKit for the core, or ArchiveKodecIo for the core plus the",
        "// kotlinx-io adapters and file sources. Not both: each carries a Kotlin runtime.",
        "let package = Package(",
        '    name: "ArchiveKodec",',
        "    products: [",
    ]
    lines += [f'        .library(name: "{name}", targets: ["{name}"]),' for name in targets]
    lines += ["    ],", "    targets: ["]
    lines += [f"        {target}," for target in targets.values()]
    lines += ["    ]", ")", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--url", help="download folder of the zips, such as a release's; omit for local paths")
    args = parser.parse_args()
    OUTPUT.mkdir(parents=True, exist_ok=True)
    targets = {}
    sums = []
    for name, source in FRAMEWORKS.items():
        archive = OUTPUT / f"{name}.xcframework.zip"
        zip_framework(source, archive)
        checksum = hashlib.sha256(archive.read_bytes()).hexdigest()
        sums.append(f"{checksum}  {archive.name}")
        if args.url:
            url = args.url.rstrip("/") + "/" + archive.name
            targets[name] = f'.binaryTarget(name: "{name}", url: "{url}", checksum: "{checksum}")'
        else:
            targets[name] = f'.binaryTarget(name: "{name}", path: "{archive.name}")'
    (OUTPUT / "Package.swift").write_text(manifest(targets))
    (OUTPUT / "checksums.txt").write_text("\n".join(sums) + "\n")
    print(f"Wrote {OUTPUT}/Package.swift", flush=True)
    for line in sums:
        print(line, flush=True)


if __name__ == "__main__":
    try:
        main()
    except (subprocess.CalledProcessError, RuntimeError, OSError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
